<?php
// File to parse MD response into HTML

namespace local_ragassistant\local;

defined('MOODLE_INTERNAL') || die();

use League\CommonMark\Environment\Environment;
use League\CommonMark\Extension\CommonMark\CommonMarkCoreExtension;
use League\CommonMark\MarkdownConverter;
use League\CommonMark\Extension\Table\TableExtension;
use League\CommonMark\Extension\Autolink\AutolinkExtension;
use League\CommonMark\Extension\Strikethrough\StrikethroughExtension;

require_once(dirname($CFG->dirroot) . '/vendor/autoload.php');

/**
 * Converts Markdown responses from the RAG assistant into HTML.
 *
 * @package local_ragassistant
 */
final class markdown_renderer {

    /**
     * Convert Markdown into HTML.
     * @param string $markdown Raw Markdown generated by Qwen.
     * @return string Rendered HTML.
     */
    public static function render(
        string $markdown,
        ?\context $context = null
    ): string {
        // Limit the response size to prevent excessive processing.
        $markdown = substr($markdown, 0, 100000);

        // Qwen commonly returns LaTeX with dollar delimiters, while Moodle's
        // MathJax filter supports \( \), \[ \], and $$ by default. Normalize
        // dollar-delimited formulas before CommonMark parses the content.
        $markdown = preg_replace(
            '/\$\$([\s\S]*?)\$\$/u',
            '\\\\[$1\\\\]',
            $markdown
        );
        $markdown = preg_replace(
            '/(?<!\$)\$([^\$\r\n]+?)\$(?!\$)/u',
            '\\\\($1\\\\)',
            $markdown
        );

        // CommonMark treats MathJax's escaped delimiters as Markdown escapes.
        // Replace them while parsing so the delimiters reach MathJax unchanged.
        $mathdelimiters = [
            '\\(' => 'RAGASSISTANTMATHINLINEOPEN',
            '\\)' => 'RAGASSISTANTMATHINLINECLOSE',
            '\\[' => 'RAGASSISTANTMATHDISPLAYOPEN',
            '\\]' => 'RAGASSISTANTMATHDISPLAYCLOSE',
        ];
        $markdown = str_replace(
            array_keys($mathdelimiters),
            array_values($mathdelimiters),
            $markdown
        );

        // Configure the Markdown parser with security and formatting options
        $config = [
            'html_input' => 'escape',
            'allow_unsafe_links' => false,
            'max_nesting_level' => 20,
        ];

        $environment = new Environment($config);
        
        // Add extensions for tables, autolinks, and strikethrough formatting
        $environment->addExtension(new CommonMarkCoreExtension());
        $environment->addExtension(new TableExtension());
        $environment->addExtension(new AutolinkExtension());
        $environment->addExtension(new StrikethroughExtension());

        // initialize the Markdown converter with the configured environment
        $converter = new MarkdownConverter($environment);

        // Convert Markdown to HTML.
        $html = $converter->convert($markdown)->getContent();
        $html = str_replace(
            array_values($mathdelimiters),
            array_keys($mathdelimiters),
            $html
        );

        // Sanitize and run Moodle's filters so MathJax marks the equations and
        // ensures its loader is available for both initial and AJAX responses.
        return format_text(
            clean_text($html, FORMAT_HTML),
            FORMAT_HTML,
            ['context' => $context ?? \context_system::instance()]
        );
    }
}
